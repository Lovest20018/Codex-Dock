"""Build the Dock Android APK from pinned upstream helpers and Dock-owned UI.

No SDK installation or live application configuration is performed.
Signing keys must already exist outside the checkout; see init-android-signing.ps1.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import zipfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/CodexAndroid'
UPSTREAM = ROOT / 'src/CodexMobile/upstream'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--jdk', type=Path, default=os.environ.get('JAVA_HOME'))
    parser.add_argument('--sdk', type=Path, default=os.environ.get('ANDROID_HOME'))
    parser.add_argument('--zxing', type=Path, default=ROOT / 'artifacts/android-deps/zxing-core-3.5.3.jar')
    parser.add_argument('--signing-home', type=Path, default=Path(os.environ.get('LOCALAPPDATA', str(ROOT / 'artifacts'))) / 'CodexDock/android-signing')
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'artifacts')
    parser.add_argument('--allow-dirty', action='store_true', help='Local validation only; not a release build.')
    args = parser.parse_args()
    if not args.jdk or not args.sdk:
        parser.error('Specify --jdk and --sdk (or JAVA_HOME and ANDROID_HOME).')
    meta = json.loads((SOURCE / 'android.json').read_text(encoding='utf-8'))
    manifest_xml = ET.parse(SOURCE / 'AndroidManifest.xml').getroot()
    attr = '{http://schemas.android.com/apk/res/android}'
    sdk_xml = manifest_xml.find('uses-sdk')
    if (manifest_xml.get('package') != meta['applicationId']
            or manifest_xml.find('application').get(attr + 'label') != meta['displayName']
            or manifest_xml.get(attr + 'versionName') != meta['versionName']
            or int(manifest_xml.get(attr + 'versionCode')) != meta['versionCode']
            or int(sdk_xml.get(attr + 'minSdkVersion')) != meta['minSdk']
            or int(sdk_xml.get(attr + 'targetSdkVersion')) != meta['targetSdk']):
        raise ValueError('Android manifest and android.json identity, version or SDK differ.')
    baseline = json.loads((ROOT / 'src/CodexMobile/upstream-manifest.json').read_text(encoding='utf-8'))
    if meta['upstreamCommit'] != baseline['commit']:
        raise ValueError('Android upstream revision differs from the reviewed snapshot.')
    subprocess.run([sys.executable, '-B', ROOT / 'scripts/verify-mobile-upstream.py'], check=True, cwd=ROOT)
    dirty = subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True).strip()
    if dirty and not args.allow_dirty:
        raise ValueError('Commit the reviewed source before making a release APK (or use --allow-dirty for QA).')
    if not args.zxing.is_file() or digest(args.zxing) != meta['dependency']['sha256']:
        raise ValueError('ZXing dependency missing or checksum mismatch; use the pinned URL in android.json.')
    key = args.signing_home / 'codex-dock.p12'
    password = args.signing_home / 'store-password.txt'
    if not key.is_file() or not password.is_file():
        raise ValueError('Initialize the private signing directory first; keys are never generated by a build.')
    if key.resolve().is_relative_to(ROOT.resolve()):
        raise ValueError('Keep private signing keys outside the repository and its artifacts.')
    tools = args.sdk / 'build-tools/35.0.0'
    android = args.sdk / f'platforms/android-{meta["targetSdk"]}/android.jar'
    windows = os.name == 'nt'
    exe = '.exe' if windows else ''
    bat = '.bat' if windows else ''
    env = {**os.environ, 'JAVA_HOME': str(args.jdk.resolve()),
           'PATH': str(args.jdk.resolve() / 'bin') + os.pathsep + os.environ['PATH'],
           'CODEX_DOCK_ANDROID_STORE_PASSWORD': password.read_text(encoding='utf-8').strip()}

    def run(*command, capture=False):
        return subprocess.run([str(v) for v in command], check=True, env=env, cwd=ROOT,
                              text=True, stdout=subprocess.PIPE if capture else None).stdout

    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    apk = out / f'LovestCode-Android-{meta["versionName"]}.apk'
    if args.allow_dirty:
        apk = apk.with_stem(apk.stem + '-qa')
    with tempfile.TemporaryDirectory(prefix='android-build-', dir=out) as temporary:
        work = Path(temporary)
        for name in ('gen', 'classes', 'dex'):
            (work / name).mkdir()
        shutil.copytree(UPSTREAM / 'mobile/android/res', work / 'res')
        (work / 'res/drawable-nodpi/ic_bridge.png').unlink()
        # Overlay only owned resources; upstream assets are never rewritten in place.
        if (SOURCE / 'res').is_dir():
            shutil.copytree(SOURCE / 'res', work / 'res', dirs_exist_ok=True)
        run(tools / ('aapt2' + exe), 'compile', '--dir', work / 'res', '-o', work / 'resources.zip')
        run(tools / ('aapt2' + exe), 'link', '-I', android, '--manifest', SOURCE / 'AndroidManifest.xml',
            '--java', work / 'gen', '-o', work / 'base.apk', work / 'resources.zip')
        java = [p for p in (UPSTREAM / 'mobile/android/src').rglob('*.java')
                if p.name not in meta['javaOverrides'] + meta['excludedJava']]
        java += list((SOURCE / 'java').rglob('*.java')) + list((work / 'gen').rglob('*.java'))
        arguments = ['-encoding', 'UTF-8', '--release', '8', '-classpath', str(android) + os.pathsep + str(args.zxing.resolve()), '-d', str(work / 'classes')]
        arguments += [str(p.resolve()) for p in java]
        (work / 'javac.args').write_text('\n'.join('"' + a.replace('\\', '/') + '"' for a in arguments), encoding='utf-8')
        run(args.jdk / ('bin/javac' + exe), '@' + str(work / 'javac.args'))
        with zipfile.ZipFile(work / 'classes.jar', 'w') as archive:
            for p in sorted((work / 'classes').rglob('*.class')):
                archive.write(p, p.relative_to(work / 'classes').as_posix())
        run(tools / ('d8' + bat), '--lib', android, '--min-api', meta['minSdk'], '--output', work / 'dex', work / 'classes.jar', args.zxing.resolve())
        shutil.copy2(work / 'base.apk', work / 'unsigned.apk')
        assets = []
        for directory in (UPSTREAM / 'mobile/shared/web', UPSTREAM / 'mobile/android/assets'):
            assets += [(p, 'assets/' + p.name) for p in sorted(directory.glob('*.js'))]
        assets += [(p, 'assets/' + p.name) for p in sorted((SOURCE / 'assets').glob('*.js'))]
        assets += [(UPSTREAM / 'web/client-icons/codex.png', 'assets/codex.png'),
                   (UPSTREAM / 'mobile/NOTICE.md', 'assets/UPSTREAM-NOTICE.md'),
                   (UPSTREAM / 'LICENSE', 'assets/UPSTREAM-LICENSE.txt'),
                   (UPSTREAM / 'mobile/licenses/ZXing-LICENSE.txt', 'assets/ZXing-LICENSE.txt'),
                   (ROOT / 'LICENSE', 'assets/Dock-LICENSE.txt'),
                   (SOURCE / 'NOTICE.md', 'assets/NOTICE.md')]
        with zipfile.ZipFile(work / 'unsigned.apk', 'a', compression=zipfile.ZIP_DEFLATED) as archive:
            for path in sorted((work / 'dex').glob('*.dex')):
                archive.write(path, path.name)
            if len({name for _, name in assets}) != len(assets):
                raise ValueError('Duplicate Android asset name.')
            for path, name in assets:
                archive.write(path, name)
        run(tools / ('zipalign' + exe), '-f', '4', work / 'unsigned.apk', work / 'aligned.apk')
        run(tools / ('apksigner' + bat), 'sign', '--ks', key, '--ks-key-alias', 'codex-dock',
            '--ks-pass', 'env:CODEX_DOCK_ANDROID_STORE_PASSWORD', '--key-pass', 'env:CODEX_DOCK_ANDROID_STORE_PASSWORD', '--out', apk, work / 'aligned.apk')
        verification = run(tools / ('apksigner' + bat), 'verify', '--verbose', '--print-certs', apk, capture=True)
        expected_signer = 'Signer #1 certificate SHA-256 digest: ' + meta['signingCertificateSha256']
        if (expected_signer not in verification.splitlines()
                or 'Verified using v2 scheme (APK Signature Scheme v2): true' not in verification
                or 'Verified using v3 scheme (APK Signature Scheme v3): true' not in verification):
            raise ValueError('APK must use the existing release certificate and v2/v3 signatures.')
        run(tools / ('zipalign' + exe), '-c', '4', apk)
        badging = run(tools / ('aapt2' + exe), 'dump', 'badging', apk, capture=True)
        if (f"name='{meta['applicationId']}'" not in badging
                or f"versionName='{meta['versionName']}'" not in badging
                or f"application-label:'{meta['displayName']}'" not in badging
                or 'application-debuggable' in badging):
            raise ValueError('APK identity, display name or version mismatch.')
        inputs = [SOURCE / 'AndroidManifest.xml', SOURCE / 'android.json'] + java + [path for path, _ in assets]
        inputs = [p for p in inputs if not p.is_relative_to(work)]
        inputs += list((SOURCE / 'res').rglob('*')) + [ROOT / 'scripts/build-android.py']
        inputs += list((UPSTREAM / 'mobile/android/res').rglob('*'))
        manifest = {**meta, 'sourceCommit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
                    'dirtyBuild': bool(dirty), 'apk': apk.name, 'size': apk.stat().st_size, 'sha256': digest(apk),
                    'signatureVerification': verification.strip().splitlines(),
                    'inputs': {p.relative_to(ROOT).as_posix(): digest(p) for p in sorted(set(inputs)) if p.is_file()}}
        apk.with_suffix('.manifest.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
        apk.with_suffix('.sha256.txt').write_text(f'{digest(apk)}  {apk.name}\n', encoding='ascii')
        print(verification.strip())
        print(apk)
        print('SHA-256', digest(apk))


if __name__ == '__main__':
    build()
